test('photo crop, stack, open card and delete keep the barcode on white', async ({ page }) => {
  await boot(page, { empty: true });
  const jpeg = await makeJpeg(page, 1400, 900);
  await openManual(page, 'Тест');
  await page.click('#artRow');
  await page.click('#artColors button[data-c="#c3c4f2"]');
  await page.click('#artModeImage');
  await chooseFile(page, '#artPick', jpeg);
  await page.locator('#crop:not(.hidden)').waitFor();
  await page.waitForFunction(() => document.querySelector('#cropFrame').getBoundingClientRect().width > 80);
  await expect(page.locator('#cropTitle')).toHaveText('Кадрирование');
  await expect(page.locator('.cropbar h3')).toHaveText('Кадрирование');
  await expect(page.locator('.cropscale #cropReset')).toHaveText('Сброс');
  await shot(page, 'crop', 400);
  const before = await page.evaluate(() => window.__app.art.session().bytes);
  await page.locator('#cropZoom').evaluate(el => { el.value = '2'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await expect.poll(() => page.evaluate(() => parseFloat(document.querySelector('#cropImg').style.width))).toBeGreaterThan(120);
  await page.click('#cropReset');
  await expect.poll(() => page.evaluate(() => parseFloat(document.querySelector('#cropZoom').value))).toBe(1);
  await page.evaluate(() => {
    const frame = document.querySelector('#cropFrame');
    const r = frame.getBoundingClientRect();
    const x = r.left + r.width / 2, y = r.top + r.height / 2;
    const fire = (type, cx, cy, id) => frame.dispatchEvent(new PointerEvent(type, {
      bubbles: true, cancelable: true, clientX: cx, clientY: cy, pointerId: id, pointerType: 'touch', isPrimary: id === 1,
    }));
    fire('pointerdown', x, y - 30, 1);
    fire('pointermove', x, y + 80, 1);
    fire('pointerup', x, y + 80, 1);
  });
  await expect(page.locator('#crop:not(.hidden)')).toBeVisible();
  await expect(page.locator('#confirm')).toBeHidden();
  await expect(page.locator('#editor:not(.hidden)')).toBeVisible();
  await page.click('#cropDone');
  await expect(page.locator('#crop')).toBeHidden();
  await expect(page.locator('#artTools')).toBeVisible();
  await expect(page.locator('#artDel')).toBeVisible();
  await expect(page.locator('#artPreview')).toHaveClass(/has-bg/);
  await expect(page.locator('#artPreview .logo')).toHaveText('Т');
  await expect(page.locator('#artPreview .hole')).toHaveCount(1);
  await shot(page, 'appearance-image', 500);
  const sized = await page.evaluate(() => window.__app.art.session());
  expect(sized.bytes).toBeGreaterThan(1000);
  expect(sized.bytes).toBeLessThan(320 * 1024);
  expect(sized.w).toBeLessThanOrEqual(1000);
  expect(sized.h).toBeLessThanOrEqual(1000);
  expect(before).toBe(sized.bytes);
  const beforeLook = await page.evaluate(() => window.__app.cards().map(c => [c.id, c.uses || 0, c.order, c.bg || 0]));
  await page.click('#lookRow');
  await page.locator('#look:not(.hidden)').waitFor();
  await expect(page.locator('#look h3')).toHaveText('Карточка');
  await expect(page.locator('#lookOpen')).toHaveClass(/on/);
  await page.waitForFunction(() => document.querySelector('#lookCode').width > 8);
  const lookBg = await page.locator('#look .lookpanel').evaluate(el => getComputedStyle(el).backgroundColor);
  expect(lookBg).toBe('rgb(255, 255, 255)');
  await expect(page.locator('#lookCard')).toHaveClass(/has-bg/);
  await shot(page, 'look-open', 500);
  await page.click('#lookStack');
  await expect(page.locator('#lookOpenView')).toBeHidden();
  await expect(page.locator('#lookStackCard')).toHaveClass(/has-bg/);
  await expect(page.locator('#lookStackCard .nm')).toHaveText('Тест');
  await shot(page, 'look-stack', 400);
  await page.click('#lookBack');
  await expect(page.locator('#look')).toBeHidden();
  await expect(page.locator('#art:not(.hidden)')).toBeVisible();
  expect(await page.evaluate(() => window.__app.cards().map(c => [c.id, c.uses || 0, c.order, c.bg || 0]))).toEqual(beforeLook);
  await page.click('#artDone');
  await expect(page.locator('#art')).toBeHidden();
  await expect(page.locator('#edPreview')).toHaveClass(/has-bg/);
  await expect(page.locator('#artVal')).toHaveText('Картинка');
  expect(await page.evaluate(() => window.__app.cards().length)).toBe(0);
  expect(await page.evaluate(() => window.__app.cards().reduce((s, c) => s + (c.uses || 0), 0))).toBe(0);
  await page.locator('#form button[type="submit"]').click();
  await expect(page.locator('#editor')).toBeHidden();
  await expect(page.locator('#stack .card.has-bg')).toHaveCount(1);
  const saved = await page.evaluate(() => {
    const c = window.__app.cards()[0];
    return { bg: c.bg, color: c.color, uses: c.uses || 0, len: JSON.stringify(c).length, mirror: localStorage.getItem('mirror') || '' };
  });
  expect(saved.bg).toBe(1);
  expect(saved.color.toLowerCase()).toBe('#c3c4f2');
  expect(saved.uses).toBe(0);
  expect(saved.len).toBeLessThan(4096);
  expect(saved.mirror.includes('data:image')).toBe(false);
  await hidePill(page);
  await shot(page, 'stack-with-photo', 400);
  await page.locator('#stack .card').click();
  await page.locator('#viewer:not(.hidden)').waitFor();
  await page.waitForFunction(() => document.querySelector('#vCode').width > 8);
  const panel = await page.locator('#viewer .panel').evaluate(el => getComputedStyle(el).backgroundColor);
  expect(panel).toBe('rgb(255, 255, 255)');
  await expect(page.locator('.panel #vCode')).toHaveCount(1);
  await expect(page.locator('#stack .card canvas')).toHaveCount(0);
  const once = await page.evaluate(() => window.__app.cards()[0].uses);
  expect(once).toBe(1);
  await shot(page, 'open-card-barcode', 400);
  await page.waitForTimeout(450);
  await page.locator('#stack .card').click();
  await expect(page.locator('#viewer')).toBeHidden();
  await page.locator('#stack .card').click();
  await page.locator('#viewer:not(.hidden)').waitFor();
  await page.click('#editBtn');
  await page.locator('#editor:not(.hidden)').waitFor();
  await page.click('#artRow');
  await page.click('#artDel');
  await expect(page.locator('#artPick')).toBeVisible();
  await expect(page.locator('#artPreview')).not.toHaveClass(/has-bg/);
  await page.click('#artModeColor');
  await expect(page.locator('#artColors button[data-c="#c3c4f2"]')).toHaveClass(/on/);
  await page.click('#artDone');
  await page.locator('#form button[type="submit"]').click();
  await expect(page.locator('#stack .card.has-bg')).toHaveCount(0);
  const cleared = await page.evaluate(async () => {
    const c = window.__app.cards()[0];
    const blob = await window.__app.backup.bgGet(c.id);
    return { bg: c.bg || 0, color: c.color, blob: blob && blob.size || 0 };
  });
  expect(cleared.bg).toBe(0);
  expect(cleared.color.toLowerCase()).toBe('#c3c4f2');
  expect(cleared.blob).toBe(0);
});

test('crop cancel keeps the previous picture and a bad file does not', async ({ page }) => {
  await boot(page, { empty: true });
  const first = await makeJpeg(page, 900, 600);
  const second = await makeJpeg(page, 500, 800);
  await openManual(page);
  await page.click('#artRow');
  await page.click('#artModeImage');
  await chooseFile(page, '#artPick', first);
  await page.locator('#crop:not(.hidden)').waitFor();
  await page.click('#cropDone');
  const kept = await page.evaluate(() => window.__app.art.session().bytes);
  await chooseFile(page, '#artReplace', second);
  await page.locator('#crop:not(.hidden)').waitFor();
  await page.click('#cropCancel');
  await expect(page.locator('#crop')).toBeHidden();
  await expect(page.locator('#art:not(.hidden)')).toBeVisible();
  expect(await page.evaluate(() => window.__app.art.session().bytes)).toBe(kept);
  await chooseFile(page, '#artReplace', Buffer.from('this is not an image at all!!'), 'note.jpg');
  await expect(page.locator('#artMsg')).toContainText('Не удалось прочитать');
  await expect(page.locator('#crop')).toBeHidden();
  expect(await page.evaluate(() => window.__app.art.session().bytes)).toBe(kept);
  await shot(page, 'unreadable-file', 300);
});
