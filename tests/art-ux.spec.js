const { test, expect } = require('@playwright/test');
const { boot, shot, makeJpeg, openManual, chooseFile, hidePill } = require('./helpers');

test('seed cards, search and METRO stay color cards', async ({ page }) => {
  await boot(page);
  await expect(page.locator('#stack .card').first()).toBeVisible();
  await expect(page.locator('#stack .card.has-bg')).toHaveCount(0);
  await expect(page.locator('#stack .hole')).toHaveCount(0);
  const metro = await page.evaluate(() => window.__app.cards().find(c => c.name === 'METRO'));
  expect(metro.format).toBe('ITF');
  expect(metro.number).toBe('6430104400975613021711');
  expect(metro.bg).toBeFalsy();
  const seed = await page.evaluate(() => (window.SEED || []).some(s => s.name === 'METRO' && s.format === 'ITF'));
  expect(seed).toBe(true);
  const before = await page.evaluate(() => window.__app.cards().map(c => [c.id, c.uses || 0, c.order]));
  await shot(page, 'stack-colors');
  await page.click('#searchBtn');
  await page.fill('#search', 'metro');
  await expect(page.locator('#stack .card')).toHaveCount(1);
  await expect(page.locator('#stack .fmt')).toHaveText('ITF');
  await page.click('#searchCancel');
  await expect(page.locator('#stack .card')).toHaveCount(before.length);
  const after = await page.evaluate(() => window.__app.cards().map(c => [c.id, c.uses || 0, c.order]));
  expect(after).toEqual(before);
  expect(await page.evaluate(() => localStorage.getItem('manualOrder'))).toBeNull();
});

